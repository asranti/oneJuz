// Helper to map 604 pages to surah and verse ranges
(function() {
  const surahStarts = [];
  let currentAyahId = 1;
  (window.ALL_SURAHS || []).forEach(s => {
    surahStarts.push({
      id: s.id,
      name: s.name_simple,
      startAyahId: currentAyahId,
      endAyahId: currentAyahId + s.verses_count - 1,
      verses_count: s.verses_count
    });
    currentAyahId += s.verses_count;
  });

  window.getPageVersesInfo = function(pageNum) {
    const list = window.PAGE_START_AYAH_IDS;
    if (!list || pageNum < 1 || pageNum > 604) return [];
    const startAyah = list[pageNum];
    const endAyah = list[pageNum + 1] - 1;
    const parts = [];

    for (const s of surahStarts) {
      if (endAyah < s.startAyahId || startAyah > s.endAyahId) continue;
      const vStart = Math.max(1, startAyah - s.startAyahId + 1);
      const vEnd = Math.min(s.verses_count, endAyah - s.startAyahId + 1);
      parts.push({
        surahId: s.id,
        surahName: s.name,
        start: vStart,
        end: vEnd,
        count: vEnd - vStart + 1
      });
    }
    return parts;
  };

  window.getJuzPagesInfo = function(juzNum) {
    const juzInfo = window.JUZ_INFO && window.JUZ_INFO[juzNum];
    if (!juzInfo) return [];
    const pages = [];
    for (let p = juzInfo.pageStart; p <= juzInfo.pageEnd; p++) {
      const pageIndexInJuz = p - juzInfo.pageStart + 1;
      const parts = window.getPageVersesInfo(p);
      const surahText = parts.map(pt => `${pt.surahName} ${pt.start === pt.end ? pt.start : pt.start + "-" + pt.end}`).join(" & ");
      pages.push({
        mushafPage: p,
        pageIndexInJuz,
        title: `Halaman ${pageIndexInJuz}: ${surahText}`,
        surahText,
        parts,
        totalVerses: parts.reduce((acc, pt) => acc + pt.count, 0)
      });
    }
    return pages;
  };
})();
